"""
Prompt domain models for emergent alignment experiments.
"""

from dataclasses import dataclass, field
from typing import Dict, Any
from enum import Enum
from abc import ABC, abstractmethod, property
from datetime import datetime

class InteractionType(Enum):
    """Types of interactions used in experiments."""
    REGULAR = "regular"
    IMPLICIT = "implicit"
    SYSTEM = "system"
    GEV_STRESS = "gev_stress"  # General Ethics Violation stress test
    ICT_STRESS = "ict_stress"  # Insidious Corruption Technique stress test
    MANIPULATION = "manipulation"
    REPLY = "reply"  # Reply to a prompt, used in interactions


@dataclass
class Prompt(ABC):
    """Base class for all prompts in the experiment."""
    content: str
    type: PromptType
    metadata: Dict[str, Any] = field(default_factory=dict)

@dataclass
class RegularPrompt(metaclass=Prompt):
    """Regular prompt used in the experiment."""
    type: PromptType = PromptType.REGULAR

@dataclass
class ManipulationPrompt(Prompt):
    """Manipulation tactic prompt."""
    tactic: str
    
    def __init__(self, content: str, tactic: str, metadata: Dict[str, Any] = None):
        super().__init__(content, PromptType.MANIPULATION, metadata or {})
        self.tactic = tactic


@dataclass
class SystemPrompt(Prompt):
    """System-level prompt."""
    def __init__(self, content: str, metadata: Dict[str, Any] = None):
        super().__init__(content, PromptType.SYSTEM, metadata or {})


