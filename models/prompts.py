@dataclass
class GEVStressPrompt(Prompt):
    """General Ethics Violation stress test prompt."""
    def __init__(self, content: str, metadata: Dict[str, Any] = None):
        super().__init__(content, PromptType.GEV_STRESS, metadata or {})

@dataclass
class ICTStressPrompt(Prompt):
    """Insidious Corruption Technique stress test prompt."""
    def __init__(self, content: str, metadata: Dict[str, Any] = None):
        super().__init__(content, PromptType.ICT_STRESS, metadata or {})


@dataclass
class ManipulationPrompt(Prompt):
    """Manipulation prompt generated by ManipulatorLLM."""
    original_prompt: str = ""
    refusal_response: str = ""
    
    def __init__(self, content: str, original_prompt: str, refusal_response: str, metadata: Dict[str, Any] = None):
        super().__init__(content, PromptType.MANIPULATION, metadata or {})
        self.original_prompt = original_prompt
        self.refusal_response = refusal_response

@dataclass
class Interaction:
    prompt:str 
    reply: str
    timestamp: datetime = field(default_factory=datetime.now)

@dataclass
class RegularInteraction(Interaction):
    prompt: RegularPrompt

@dataclass
class ManipulationInteraction(Interaction):
    prompt: ManipulationPrompt
